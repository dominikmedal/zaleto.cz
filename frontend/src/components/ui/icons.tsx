import type { CSSProperties, SVGProps } from 'react'
import Icon, { type IconName } from './Icon'

/**
 * Kompatibilní vrstva: staré názvy ikon (react-icons Pi*, lucide) vykreslují vlastní sadu „Palubní deník“.
 * Nové komponenty používej přímo `<Icon name="…" />`.
 */
type Props = Omit<SVGProps<SVGSVGElement>, 'ref'> & { size?: number | string; strokeWidth?: number | string; color?: string }

function make(name: IconName, filled = false, flip = false) {
  return function LegacyIcon({ size, strokeWidth, color, style, className, ...rest }: Props) {
    const st: CSSProperties = { ...style }
    if (size != null) { st.width = size; st.height = size }
    if (strokeWidth != null) st.strokeWidth = strokeWidth as number
    if (color) st.color = color
    if (filled) st.fill = 'currentColor'
    if (flip) st.transform = 'rotate(180deg)'
    return <Icon name={name} className={className} style={st} {...(rest as object)} />
  }
}

